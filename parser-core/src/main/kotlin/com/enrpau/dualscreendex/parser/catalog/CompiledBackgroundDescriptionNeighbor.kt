        0x46a0, 0x6834, 0x7a0, 0xf85, 0x2d03, 0xd838, 0x721, 0xf89, 0x5e2, 0xed2, 0x563,
        0xf9b, 0x520, 0xfc0, 0x9000, 0x4a0, 0xf80, 0x9001, 0x9702, 0x9703, 0x1c28,
        -1, -1, 0x12c, 0x464d, 0x1963, 0x6832, 0x212, 0xd92, 0x8818, 0x4d1a, 0x1c29,
        0x4008, 0x4310, 0x8018, 0x7858, 0x223d, 0x4252, 0x1c11, 0x4008, 0x7058, 0x6818,
        0x4915, 0x4008, 0x6018, 0x4648, 0x3004, 0x1820, 0x6007, 0x4648, 0x3008, 0x1820,
