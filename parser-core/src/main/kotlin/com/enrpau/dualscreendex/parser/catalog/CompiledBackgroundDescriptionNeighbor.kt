package com.enrpau.dualscreendex.parser.catalog

import com.enrpau.dualscreendex.parser.io.RomImage

/** The four-entry, four-byte BG-template consumer, including stack-correct child returns. */
internal object CompiledBackgroundDescriptionNeighbor {
    fun matches(rom: RomImage, site: Int): Boolean {
        if (!ops(rom, site + 2, intArrayOf(0x2000, 0x2204))) return false
        val entry = call(rom, site + 6) ?: return false
        if (!ops(rom, entry, BODY)) return false
        val state = literal(rom, entry + 36) ?: return false
        if (!ram(state, 0x40) || literal(rom, entry + 42) != state + 0x50 ||
            literal(rom, entry + 152) != state + 12 ||
            literal(rom, entry + 106) != 0xfffffc00L || literal(rom, entry + 130) != 0x3fffL) return false
        val mode = call(rom, entry + 22) ?: return false
        val reset = call(rom, entry + 26) ?: return false
        val setter = call(rom, entry + 88) ?: return false
        if (!ops(rom, mode, intArrayOf(0x0600, 0x0e00, 0x4b03, 0x8a1a, 0x4903, 0x4011,
                0x4301, 0x8219, 0x4770)) || literal(rom, mode + 8) != 0xfff8L) return false
        val modeState = literal(rom, mode + 4) ?: return false
        if (!ram(modeState, 20)) return false
        if (!ops(rom, reset, intArrayOf(0xb500, 0x4a05, 0x4805, 0x6800, 0x1c11, 0x310c,
                0x6008, 0x3904, 0x4291, 0xdafb, 0xbc01, 0x4700)) ||
            literal(rom, reset + 2) != modeState) return false
        val initial = literal(rom, reset + 4) ?: return false
        if (initial - 0x08000000L !in 0..(rom.size - 4).toLong()) return false
        if (!ops(rom, setter, SETTER) || literal(rom, setter + 86) != modeState) return false
        val checkedId = call(rom, setter + 72) ?: return false
        return ops(rom, checkedId, intArrayOf(0xb500, 0x0600, 0x0e00, 0x2803, 0xd801,
            0x2000, 0xe000, 0x2001, 0xbc02, 0x4708))
    }

    private fun ram(address: Long, width: Int): Boolean = address % 4 == 0L &&
        (address in 0x02000000L..0x02040000L - width || address in 0x03000000L..0x03008000L - width)

    // -1 marks only BL halfwords. Every such pair is decoded and its callee proven above.
    private fun ops(rom: RomImage, start: Int, expected: IntArray): Boolean =
        start >= 0 && start.toLong() + expected.size * 2 <= rom.size &&
            expected.indices.all { expected[it] == -1 || rom.u16le(start + it * 2) == expected[it] }

    private fun literal(rom: RomImage, site: Int): Long? {
        if (site !in 0..rom.size - 2) return null
        val op = rom.u16le(site)
        if (op and 0xf800 != 0x4800) return null
        val target = ((site + 4) and -4) + (op and 255) * 4
        return target.takeIf { it in 0..rom.size - 4 }?.let(rom::u32le)
    }

    private fun call(rom: RomImage, site: Int): Int? {
        if (site !in 0..rom.size - 4) return null
        val high = rom.u16le(site)
        val low = rom.u16le(site + 2)
        if (high and 0xf800 != 0xf000 || low and 0xf800 != 0xf800) return null
        var delta = ((high and 0x7ff) shl 12) or ((low and 0x7ff) shl 1)
        if (delta and 0x400000 != 0) delta -= 0x800000
        return (site + 4 + delta).takeIf { it in 0..rom.size - 2 }
    }

    // r1 array -> r6, u8 r2 count -> r8; all fields, +4 stride, backedge, and frame restoration.
    private val BODY = intArrayOf(
