    private val bySha = all.associateBy { it.sha256.lowercase() }

    fun bySha256(sha256: String): RomProfile? = bySha[sha256.lowercase()]

    fun forFamily(family: EngineFamily): List<RomProfile> = all.filter { it.family == family }

    private fun gbProfile(
